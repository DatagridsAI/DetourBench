#!/usr/bin/env python3
"""Build TASKS.md: one authoritative row per task.

The suite's task count has been quoted three different ways in one day
because it lived in nobody's file - it was inferred each time from the
registry, a directory listing, or an episode count. This writes it down:
every registered task, its family, its corpus, its category, its provable
lower bound, and whether it passes structural validation.

Runs one task at a time and writes incrementally, because computing a
bound is a BFS over (visited, inventory) states and doing two hundred of
them at once put the machine at load 116.
"""
import collections, json, os, random, re, subprocess, sys, time
HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
sys.path.insert(0, HERE)
from generate import build_graph, compute_lower_bound            # noqa: E402
import generate                                                  # noqa: E402

CN = {"latest": "Currency", "breadth": "Breadth",
      "sufficiency": "Sufficiency", "disposal": "Disposition",
      "depth": "Depth", "time": "Time"}
FAM = {"adv": "OSV advisory", "iss": "Apache Jira", "enc": "Synthea record"}

src = open("regulatory_tasks.py", encoding="utf-8").read()
tasks = []
for tag, cat in re.findall(r'"(t\d+)_([a-z_]+)": _bind_corpus', src):
    if cat in CN:
        tasks.append((tag + "_" + cat, "CFR", tag, CN[cat],
                      "corpora_ecfr_%s.json" % tag))
for name, corpus in re.findall(r'"([^"]+)": _bind_file\("([^"]+)"', src):
    cat = name.rsplit("_", 1)[-1]
    if cat in CN:
        tasks.append((name, FAM.get(name[:3], "?"),
                      name[3:].rsplit("_", 1)[0], CN[cat], corpus))

print("%d tasks to measure" % len(tasks), flush=True)
rows, t0 = [], time.time()
for i, (name, fam, corpus_tag, cat, corpus_file) in enumerate(tasks, 1):
    lb = nodes = None
    err = ""
    try:
        g, m = build_graph(random.Random(0), "finance_pipeline", name)
        lb, _p = compute_lower_bound(g, m)
        nodes = len(g["nodes"])
    except Exception as e:
        err = str(e)[:40]
    rows.append(dict(name=name, family=fam, corpus=corpus_tag,
                     category=cat, bound=lb, nodes=nodes, error=err,
                     corpus_file=corpus_file))
    if i % 20 == 0:
        print("  %d/%d  (%.0fs)" % (i, len(tasks), time.time() - t0),
              flush=True)
        json.dump(rows, open("/tmp/manifest_partial.json", "w"))

json.dump(rows, open("/tmp/manifest.json", "w"), indent=1)
good = [r for r in rows if r["bound"]]
print("built %d/%d" % (len(good), len(rows)), flush=True)

# --- render
by_fam = collections.defaultdict(lambda: collections.defaultdict(list))
for r in good:
    by_fam[r["family"]][r["category"]].append(r)

cats = ["Currency", "Breadth", "Sufficiency", "Disposition", "Depth", "Time"]
fams = ["CFR", "OSV advisory", "Apache Jira", "Synthea record"]
EDGE = {
    "CFR": "citation between sections of one Code",
    "OSV advisory": "overlap in affected version ranges",
    "Apache Jira": "tracker link: blocks, duplicates, depends",
    "Synthea record": "a condition or medication two encounters share",
}

out = ["# DetourBench — every task",
       "",
       "Generated by `build_manifest.py`. One row per task; a task is one",
       "(category, corpus) pair. Bounds are the provable minimum action",
       "count at instance seed 0 — instances of the same task vary, so",
       "treat these as representative rather than fixed.",
       "",
       "## Totals", "",
       "| Family | " + " | ".join(cats) + " | Total | Edge means |",
       "|---|" + "---|" * (len(cats) + 2)]
grand = collections.Counter()
for f in fams:
    row = [len(by_fam[f][c]) for c in cats]
    grand.update({c: n for c, n in zip(cats, row)})
    out.append("| %s | %s | **%d** | %s |"
               % (f, " | ".join(str(n) for n in row), sum(row), EDGE[f]))
out.append("| **Total** | %s | **%d** | |"
           % (" | ".join("**%d**" % grand[c] for c in cats),
              sum(grand.values())))

out += ["", "## Every task", "",
        "| Task | Family | Corpus | Category | Bound | Nodes |",
        "|---|---|---|---|---|---|"]
for r in sorted(good, key=lambda r: (r["family"], r["category"], r["name"])):
    out.append("| `%s` | %s | %s | %s | %s | %s |"
               % (r["name"], r["family"], r["corpus"], r["category"],
                  r["bound"], r["nodes"]))

failed = [r for r in rows if not r["bound"]]
if failed:
    out += ["", "## Registered but not building", "",
            "Kept in the registry so the reason stays visible.", "",
            "| Task | Reason |", "|---|---|"]
    for r in sorted(failed, key=lambda r: r["name"]):
        out.append("| `%s` | %s |" % (r["name"], r["error"]))

open("TASKS.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote TASKS.md: %d tasks, %d not building" % (len(good), len(failed)))
