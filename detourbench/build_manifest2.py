#!/usr/bin/env python3
"""Build TASKS.md from the registry, without computing a bound per task.

The first version measured a provable lower bound for all 207 tasks in one
pass. That is a BFS over (visited, inventory) states each time, and it took
the machine down twice - the second time under `nice -n 15`, which limits
CPU scheduling and does nothing about the rest.

The bound is not what a manifest is for. What it has to answer is: which
tasks exist, which document each comes from, and which category it belongs
to. All of that is in the registry and costs nothing to read. Bounds are
sampled - two per (family, category) cell - which is enough to show a cell
is not degenerate without paying for 207 searches.
"""
import collections, json, os, random, re, sys, time

HERE = os.path.dirname(os.path.abspath(__file__))
os.chdir(HERE)
sys.path.insert(0, HERE)

CN = {"latest": "Currency", "breadth": "Breadth",
      "sufficiency": "Sufficiency", "disposal": "Disposition",
      "depth": "Depth", "time": "Time"}
FAM = {"adv": "OSV advisory", "iss": "Apache Jira", "enc": "Synthea record"}
EDGE = {
    "CFR": "citation between sections of one Code",
    "OSV advisory": "overlap in affected version ranges",
    "Apache Jira": "tracker link: blocks, duplicates, depends",
    "Synthea record": "a condition or medication two encounters share",
}

src = open("regulatory_tasks.py", encoding="utf-8").read()
tasks = []
for tag, cat in re.findall(r'"(t\d+)_([a-z_]+)": _bind_corpus', src):
    if cat in CN:
        tasks.append(dict(name="%s_%s" % (tag, cat), family="CFR",
                          corpus=tag, category=CN[cat],
                          corpus_file="corpora_ecfr_%s.json" % tag))
for name, cf in re.findall(r'"([^"]+)": _bind_file\("([^"]+)"', src):
    cat = name.rsplit("_", 1)[-1]
    if cat in CN and name[:3] in FAM:
        tasks.append(dict(name=name, family=FAM[name[:3]],
                          corpus=name[3:].rsplit("_", 1)[0],
                          category=CN[cat], corpus_file=cf))
print("%d tasks in the registry" % len(tasks), flush=True)

# Bounds are omitted entirely. A single compute_lower_bound is a BFS
# over (visited, inventory) states and is expensive on a 75-node graph;
# even two per cell did not finish. The manifest does not need them - what
# it has to answer is which tasks exist, from which document, in which
# category, and that is all in the registry. Per-category bound ranges are
# already recorded in STATUS.md from when they were measured.
bounds = {}

cats = ["Currency", "Breadth", "Sufficiency", "Disposition", "Depth", "Time"]
fams = ["CFR", "OSV advisory", "Apache Jira", "Synthea record"]
counts = collections.Counter((t["family"], t["category"]) for t in tasks)

out = ["# DetourBench — every task", "",
       "Generated by `build_manifest2.py` from the registry. A task is",
       "one (category, corpus) pair.", "",
       "Bounds are deliberately absent. Computing one is a breadth-first",
       "search over (visited, inventory) states, and doing it per task",
       "took the machine down twice - the second time under `nice -n 15`,",
       "which limits CPU scheduling and nothing else. Per-category bound",
       "ranges are in `STATUS.md`, measured when the categories were",
       "built.", "",
       "## Coverage", "",
       "| Family | " + " | ".join(cats) + " | Total | An edge means |",
       "|---|" + "---|" * (len(cats) + 2)]
grand = collections.Counter()
for f in fams:
    row = [counts[(f, c)] for c in cats]
    for c, n in zip(cats, row):
        grand[c] += n
    out.append("| %s | %s | **%d** | %s |"
               % (f, " | ".join(str(n) for n in row), sum(row), EDGE[f]))
out.append("| **Total** | %s | **%d** | |"
           % (" | ".join("**%d**" % grand[c] for c in cats),
              sum(grand.values())))

out += ["", "## Every task", "",
        "| Task | Family | Corpus | Category |", "|---|---|---|---|"]
for t in sorted(tasks, key=lambda t: (t["family"], t["category"], t["name"])):
    out.append("| `%s` | %s | %s | %s |"
               % (t["name"], t["family"], t["corpus"], t["category"]))

open("TASKS.md", "w", encoding="utf-8").write("\n".join(out) + "\n")
json.dump(tasks, open("tasks_manifest.json", "w"), indent=1)
print("\nwrote TASKS.md (%d tasks) and tasks_manifest.json"
      % len(tasks), flush=True)
